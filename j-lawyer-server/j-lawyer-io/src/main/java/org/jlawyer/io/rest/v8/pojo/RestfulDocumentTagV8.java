package org.jlawyer.io.rest.v8.pojo;

/**
 * A tag (Etikett) of a case document: its name and, for multi-value tags, its value.
 *
 * @author jens
 */
public class RestfulDocumentTagV8 {

    private String name;
    private String value;

    public RestfulDocumentTagV8() {
    }

    public RestfulDocumentTagV8(String name, String value) {
        this.name = name;
        this.value = value;
    }

    public String getName() { return name; }
    public void setName(String name) { this.name = name; }

    public String getValue() { return value; }
    public void setValue(String value) { this.value = value; }
}
