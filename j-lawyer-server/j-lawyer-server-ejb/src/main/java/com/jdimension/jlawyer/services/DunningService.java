    /**
     * Writes one entry of the journal.
     *
     * Every move of a procedure is recorded with the procedural date, the user and whether a person
     * entered it or a court message reported it. That last distinction is what a later question about
     * the procedure turns on.
     *
     * @param dunningCase the procedure
     * @param previous the status held before, or null for the first entry
     * @param status the status reached
     * @param eventDate the procedural date
     * @param source whether a person or a court message is behind it
     * @param comment a note, or null
     */
    private void journal(DunningCase dunningCase, DunningCaseStatus previous, DunningCaseStatus status,
            Date eventDate, DunningStatusSource source, String comment) {

        DunningCaseEvent event = new DunningCaseEvent();
        event.setId(new StringGenerator().getID().toString());
        event.setDunningCase(dunningCase);
        event.setPreviousStatus(previous);
        event.setNewStatus(status);
        event.setEventDate(eventDate);
        event.setRecorded(new Date());
        event.setSource(source);
        event.setComment(comment);
        try {
            event.setRecordedBy(this.context.getCallerPrincipal().getName());
        } catch (Throwable t) {
            log.warn("Unable to determine caller when journalling a dunning status change", t);
        }
        this.dunningCaseEventsFacade.create(event);
    }

    /**
     * Writes a procedural date onto the field belonging to the event, which is what the deadline
     * engine computes from.
     */
    /**
     * Carries the date the Mahnbescheid was served into the interest rules that wait for it.
     *
     * Which rules those are is decided by {@link ServiceDateInterestPlanner}; what happens here is
     * only the loading and the writing.
     *
     * @param dunningCase the procedure whose service date has just been recorded
     * @param previousServiceDate the service date recorded before this change, or null
     * @return how many interest rules were given a start
     */
    private int startInterestOnService(DunningCase dunningCase, Date previousServiceDate) {

        if (dunningCase.getStatus() != DunningCaseStatus.MB_SERVED
                || dunningCase.getMbServedDate() == null || dunningCase.getLedger() == null) {
            return 0;
        }
        try {
            List<ClaimComponent> components
                    = new ArrayList<>(this.claimComponentsFacade.findByLedger(dunningCase.getLedger()));
            List<InterestRule> rules = new ArrayList<>();
            for (ClaimComponent component : components) {
                rules.addAll(this.interestRulesFacade.findByComponent(component));
            }
            List<InterestRule> started = new ServiceDateInterestPlanner().rulesStartedBy(
                    components, rules, previousServiceDate, dunningCase.getMbServedDate());
            for (InterestRule rule : started) {
                rule.setValidFrom(dunningCase.getMbServedDate());
                this.interestRulesFacade.edit(rule);
            }
            return started.size();
        } catch (Exception ex) {
            // the status itself is recorded either way; an interest start that could not be written
            // is a defect to fix, not a reason to lose the service date
            log.error("Unable to start interest on service for dunning case " + dunningCase.getId(), ex);
            return 0;
        }
    }

    private void applyProceduralDate(DunningCase dunningCase, DunningCaseStatus status, Date date) {
        switch (status) {
            case MB_APPLIED:
                dunningCase.setMbAppliedDate(date);
                break;
            case MB_ISSUED:
                dunningCase.setMbIssuedDate(date);
                break;
            case MB_SERVED:
                dunningCase.setMbServedDate(date);
                break;
            case OBJECTION:
                dunningCase.setObjectionDate(date);
                break;
            case VB_APPLIED:
                dunningCase.setVbAppliedDate(date);
                break;
            case VB_ISSUED:
                dunningCase.setVbIssuedDate(date);
                break;
            case VB_SERVED:
                dunningCase.setVbServedDate(date);
                break;
            case EINSPRUCH:
                dunningCase.setEinspruchDate(date);
                break;
            case REFERRED:
                dunningCase.setReferralDate(date);
                break;
            case COMPLETED:
                dunningCase.setCompletedDate(date);
                break;
            default:
                break;
        }
    }

    /**
     * An own reference the court can echo: recognisable to the firm and unique enough to match on.
     */
    private String generateOwnReference(ClaimLedger ledger) {
        String caseNumber = ledger.getArchiveFileKey() == null
                ? "" : ledger.getArchiveFileKey().getFileNumber();
        String suffix = new StringGenerator().getID().toString().replace("-", "");
        return (caseNumber == null || caseNumber.trim().isEmpty()
                ? "MB" : caseNumber.trim()) + "-" + suffix.substring(0, Math.min(8, suffix.length()));
    }

    /**
     * Assembles what the format wants to know about the lawyer filing this application.
     *
     * The identity records C07 to C09 are not written: the firm files under its own Kennziffer, and
     * the Satzbeschreibung says a Kennziffer for the Prozessbevollmächtigter closes that area. What
     * remains is C10, which the format requires per application and which therefore cannot live in
     * the Kennziffer, and the account of C11.
     *
     * The lawyer is found by the Kennziffer of the procedure, which is chosen from the users who
     * have one. Their bank details come along, so the account the defendant is told to pay into is
     * the one of the lawyer actually filing rather than something entered a second time.
     *
     * @param dunningCase the procedure
     * @return the representative, or null if there is nothing to declare and no account to name
     */
    private EdaProcessRepresentative representativeOf(DunningCase dunningCase) {

        EdaProcessRepresentative representative = new EdaProcessRepresentative();
        representative.setOwnReference(dunningCase.getOwnReference());
        representative.setOrderDate(dunningCase.getOrderDate());
        representative.setOffsetAmount(dunningCase.getOffsetAmount());
        representative.setSpecialEffortDeclared(dunningCase.isSpecialEffort());

        AppUserBean lawyer = lawyerByKennziffer(dunningCase.getKennziffer());
        if (lawyer != null) {
            representative.setSalutation(EdaProcessRepresentative.Salutation.RECHTSANWALT);
            representative.setDesignation(lawyer.getDisplayName());
            representative.setAccountHolder(EdaProcessRepresentative.AccountHolder.REPRESENTATIVE);
            representative.setIban(lawyer.getBankIban());
            representative.setBic(lawyer.getBankBic());
        }
        return representative;
    }

    /**
     * @param kennziffer the Kennziffer recorded on the procedure
     * @return the user filing under it, or null
     */
    private AppUserBean lawyerByKennziffer(String kennziffer) {
        if (kennziffer == null || kennziffer.trim().isEmpty()) {
            return null;
        }
        String wanted = kennziffer.trim();
        for (AppUserBean user : this.appUsersFacade.findAll()) {
            if (wanted.equals(user.getDunningKennziffer() == null
                    ? null : user.getDunningKennziffer().trim())) {
                return user;
            }
        }
        return null;
    }

    private DunningCase requireCase(String dunningCaseId) throws Exception {
        if (dunningCaseId == null) {
            throw new Exception("Die Mahnsache ist nicht gespeichert!");
        }
        DunningCase stored = this.dunningCasesFacade.find(dunningCaseId);
        if (stored == null) {
            throw new Exception("Die Mahnsache existiert nicht!");
        }
        if (stored.getLedger() == null || stored.getLedger().getArchiveFileKey() == null) {
            throw new Exception("Die Mahnsache ist keiner Akte zugeordnet!");
        }
        requireAccess(stored.getLedger().getArchiveFileKey());
        return stored;
    }

    @Override
    @RolesAllowed({"readArchiveFileRole"})
    public List<DunningWorklistRow> getWorklist(DunningWorklistFilter filter) throws Exception {

        DunningWorklistFilter f = filter == null ? new DunningWorklistFilter() : filter;
        List<DunningWorklistRow> rows = new ArrayList<>();
        Date today = new Date();

        for (DunningCase dunningCase : this.dunningCasesFacade.findAll()) {
            if (!matches(dunningCase, f)) {
                continue;
            }
            // the list shows the user's own work: a procedure in a case they may not open has no
            // business appearing in it, not even as a row they cannot follow
            if (!hasAccess(dunningCase)) {
                continue;
            }
            DunningWorklistRow row = toRow(dunningCase, today);
            if (f.isOverdueDeadlinesOnly() && !row.isNextDeadlineOverdue()) {
                continue;
            }
            rows.add(row);
        }

        // the most urgent first, and procedures without a deadline after those that have one
        rows.sort((a, b) -> {
            if (a.getNextDeadline() == null && b.getNextDeadline() == null) {
                return 0;
            }
            if (a.getNextDeadline() == null) {
                return 1;
            }
            if (b.getNextDeadline() == null) {
                return -1;
            }
            return a.getNextDeadline().compareTo(b.getNextDeadline());
        });
        return rows;
    }

    /**
     * Whether a procedure belongs in the list under the given filter.
     */
    private boolean matches(DunningCase dunningCase, DunningWorklistFilter f) {

        if (dunningCase.getStatus() == null) {
            return false;
        }
        if (!f.isIncludeClosed() && dunningCase.getStatus().isClosed()) {
            return false;
        }
        if (!f.getStatuses().isEmpty() && !f.getStatuses().contains(dunningCase.getStatus())) {
            return false;
        }
        if (f.getCourtXJustizId() != null && !f.getCourtXJustizId().trim().isEmpty()
                && !f.getCourtXJustizId().trim().equals(dunningCase.getCourtXJustizId())) {
            return false;
        }
        if (f.isObjectionPeriodExpiredOnly() && !objectionPeriodExpired(dunningCase)) {
            return false;
        }
        return true;
    }

    /**
     * The question the firm asks most often: is this a Mahnbescheid whose objection period has run
     * without an enforcement order having been applied for.
     *
     * The period is computed rather than read from the deadline records, so the answer does not
     * depend on whether the calendar entries were ever created.
     */
    private boolean objectionPeriodExpired(DunningCase dunningCase) {

        if (dunningCase.getStatus() != DunningCaseStatus.MB_SERVED
                || dunningCase.getMbServedDate() == null) {
            return false;
        }
        List<com.jdimension.jlawyer.pojo.DunningDeadline> deadlines =
                new DunningDeadlineCalculator().computeDeadlines(dunningCase, 0);
        for (com.jdimension.jlawyer.pojo.DunningDeadline d : deadlines) {
            if (d.getType() == com.jdimension.jlawyer.persistence.DunningDeadlineType.OBJECTION_PERIOD) {
                return d.getDeadline() != null && new Date().after(d.getDeadline());
            }
        }
        return false;
    }

    /**
     * Builds one row, including the earliest deadline still open.
     */
    private DunningWorklistRow toRow(DunningCase dunningCase, Date today) {

        DunningWorklistRow row = new DunningWorklistRow();
        row.setDunningCaseId(dunningCase.getId());
        row.setOwnReference(dunningCase.getOwnReference());
        row.setCourtName(dunningCase.getCourtName());
        row.setCourtFileNumber(dunningCase.getCourtFileNumber());
        row.setStatus(dunningCase.getStatus());
        row.setStatusDate(dunningCase.getStatusDate());
        row.setAppliedTotal(dunningCase.getAppliedTotal());

        ClaimLedger ledger = dunningCase.getLedger();
        if (ledger != null) {
            row.setLedgerId(ledger.getId());
            if (ledger.getArchiveFileKey() != null) {
                row.setCaseId(ledger.getArchiveFileKey().getId());
                row.setCaseFileNumber(ledger.getArchiveFileKey().getFileNumber());
                row.setCaseName(ledger.getArchiveFileKey().getName());
            }
            for (ClaimLedgerParty party : this.claimLedgerPartiesFacade.findByLedger(ledger)) {
                if (party.getRole() == ClaimPartyRole.CREDITOR && row.getCreditor() == null) {
                    row.setCreditor(party.getEffectiveDesignation());
                } else if (party.getRole() == ClaimPartyRole.DEBTOR && row.getDebtor() == null) {
                    row.setDebtor(party.getEffectiveDesignation());
                }
            }
        }

        for (DunningCaseDeadline deadline : this.dunningDeadlinesFacade.findByDunningCase(dunningCase)) {
            if (deadline.isClosed() || deadline.getDeadlineDate() == null) {
                continue;
            }
            if (row.getNextDeadline() == null || deadline.getDeadlineDate().before(row.getNextDeadline())) {
                row.setNextDeadline(deadline.getDeadlineDate());
                row.setNextDeadlineLabel(deadline.getDeadlineType() == null
                        ? null : deadline.getDeadlineType().getLabel());
            }
        }
        row.setNextDeadlineOverdue(row.getNextDeadline() != null && today.after(row.getNextDeadline()));
        return row;
    }

    @Override
    @RolesAllowed({"readArchiveFileRole"})
    public String exportWorklistAsCsv(List<DunningWorklistRow> rows) throws Exception {

        StringBuilder sb = new StringBuilder();
        sb.append("Akte;Bezeichnung;Gläubiger;Schuldner;Mahngericht;Geschäftsnummer;")
                .append("Geschäftszeichen;Status;Seit;Beantragt;Nächste Frist;Fristart;überfällig\n");

        if (rows != null) {
            for (DunningWorklistRow r : rows) {
                sb.append(csv(r.getCaseFileNumber())).append(";")
                        .append(csv(r.getCaseName())).append(";")
                        .append(csv(r.getCreditor())).append(";")
                        .append(csv(r.getDebtor())).append(";")
                        .append(csv(r.getCourtName())).append(";")
                        .append(csv(r.getCourtFileNumber())).append(";")
                        .append(csv(r.getOwnReference())).append(";")
                        .append(csv(r.getStatus() == null ? null : r.getStatus().getLabel())).append(";")
                        .append(csv(r.getStatusDate() == null ? null : DATE_FORMAT.format(r.getStatusDate()))).append(";")
                        .append(r.getAppliedTotal() == null ? "" : r.getAppliedTotal().toPlainString()).append(";")
                        .append(csv(r.getNextDeadline() == null ? null : DATE_FORMAT.format(r.getNextDeadline()))).append(";")
                        .append(csv(r.getNextDeadlineLabel())).append(";")
                        .append(r.isNextDeadlineOverdue() ? "ja" : "nein").append("\n");
            }
        }
        return sb.toString();
    }

    /**
     * Escapes a value for the CSV: a semicolon or a line break in a party name would otherwise shift
     * every following column of that row.
     */
    private String csv(String value) {
        if (value == null) {
            return "";
        }
        String v = value.replace("\"", "\"\"").replace("\n", " ").replace("\r", " ");
        return v.contains(";") || v.contains("\"") ? "\"" + v + "\"" : v;
    }

    /**
     * Finds the procedure a message belongs to.
     *
     * The search is deliberately across all procedures rather than within the case the file was
     * filed in. A court sends collective files - the trailer counts the messages in them - so one
     * document can carry news for many procedures in many cases. Where that document sits is
     * provenance, not context.
     *
     * The reference the court echoes is what the application sent, so it is tried first; the court's
     * file number is the fallback, since it exists only once the court has processed the application.
     *
     * @param message the message
     * @return the procedure, or null where none matches unambiguously
     */
    private DunningCase match(EdaMessage message) {

        if (message.getOwnReference() != null && !message.getOwnReference().trim().isEmpty()) {
            List<DunningCase> found = this.dunningCasesFacade.findByOwnReference(
                    message.getOwnReference().trim());
            if (found.size() == 1) {
                return found.get(0);
            }
            if (found.size() > 1) {
                // an ambiguous reference is not something to resolve by guessing
                return null;
            }
        }
        if (message.getCourtFileNumber() != null && !message.getCourtFileNumber().trim().isEmpty()) {
            List<DunningCase> found = this.dunningCasesFacade.findByCourtFileNumber(
                    message.getCourtFileNumber().trim());
            if (found.size() == 1) {
                return found.get(0);
            }
        }
        return null;
    }

    /**
     * @param dunningCase the procedure
     * @return whether the calling user may see the case it belongs to
     */
    private boolean hasAccess(DunningCase dunningCase) {
        try {
            if (dunningCase.getLedger() == null || dunningCase.getLedger().getArchiveFileKey() == null) {
                return false;
            }
            requireAccess(dunningCase.getLedger().getArchiveFileKey());
            return true;
        } catch (Exception ex) {
            return false;
        }
    }

    /**
     * How a procedure is named to the user: by its case and its own reference.
     */
    private String label(DunningCase dunningCase) {
        StringBuilder sb = new StringBuilder();
        if (dunningCase.getLedger() != null && dunningCase.getLedger().getArchiveFileKey() != null) {
            sb.append(dunningCase.getLedger().getArchiveFileKey().getFileNumber()).append(" ");
        }
        sb.append(dunningCase.getOwnReference() == null
                ? dunningCase.getId() : dunningCase.getOwnReference());
        return sb.toString().trim();
    }

    /**
     * The parties of one role, in a stable order.
     */
    private List<ClaimLedgerParty> partiesOf(List<ClaimLedgerParty> parties, ClaimPartyRole role) {
        List<ClaimLedgerParty> found = new ArrayList<>();
        for (ClaimLedgerParty p : parties) {
            if (p.getRole() == role) {
                found.add(p);
            }
        }
        return found;
    }

    /**
     * Resolves the requested claims against the ledger's own positions.
     *
     * A component that does not belong to this ledger is refused rather than silently skipped: a
     * request naming a foreign position is a mistake worth surfacing, not one to work around.
     */
    private List<EdaClaimMapper.Claim> toClaims(List<DunningClaimInput> inputs,
            List<ClaimComponent> components) throws Exception {

        List<EdaClaimMapper.Claim> claims = new ArrayList<>();
        if (inputs == null) {
            return claims;
        }
        for (DunningClaimInput input : inputs) {
            ClaimComponent component = null;
            for (ClaimComponent c : components) {
                if (c.getId().equals(input.getComponentId())) {
                    component = c;
                    break;
                }
            }
            if (component == null) {
                throw new Exception("Die Forderungsposition " + input.getComponentId()
                        + " gehört nicht zu diesem Forderungskonto!");
            }
            // an input without an amount applies for the position as it stands; writing an empty
            // amount into the record would apply for nothing at all
            EdaClaimMapper.Claim claim = new EdaClaimMapper.Claim(component,
                    input.getAmount() == null ? component.getPrincipalAmount() : input.getAmount());
            claim.setFrom(input.getFrom());
            claim.setTo(input.getTo());
            claim.setInvoiceNumber(input.getInvoiceNumber());
            claim.setInterestTo(input.getInterestTo());
            claim.setInterestStartMode(component.getInterestStartMode());
            claim.getInterestRules().addAll(this.interestRulesFacade.findByComponent(component));
            claims.add(claim);
        }
        return claims;
    }

    private String documentName(DunningCase dunningCase, String fileName) {
        return "Mahnbescheidsantrag_"
                + (dunningCase.getOwnReference() == null ? fileName : dunningCase.getOwnReference())
                + ".eda";
    }

    private String describe(DunningValidationResult validation) {
        StringBuilder sb = new StringBuilder();
        for (DunningValidationIssue issue : validation.getBlockingIssues()) {
            sb.append("\n").append(issue.getField()).append(": ").append(issue.getMessage());
        }
        return sb.toString();
    }

    /**
     * Verifies that the calling user may see this case.
     *
     * The role annotation only establishes that a user may read cases at all. Whether this
     * particular one is accessible depends on the groups it is restricted to, so it has to be
     * checked separately - otherwise a user excluded from a case could still inspect its dunning
     * procedure.
     *
     * @param caseFile the case the procedure belongs to
     * @throws Exception if the user may not access it
     */
    private void requireAccess(ArchiveFileBean caseFile) throws Exception {

        String principalId = this.context.getCallerPrincipal().getName();
        List<Group> userGroups = new ArrayList<>();
        try {
            userGroups = this.securityFacade.getGroupsForUser(principalId);
        } catch (Throwable t) {
            log.error("Unable to determine groups for user " + principalId, t);
        }
        if (!SecurityUtils.checkGroupsForCase(userGroups, caseFile, this.caseGroupsFacade)) {
            throw new Exception("Sie haben keinen Zugriff auf diese Akte!");
        }
    }
