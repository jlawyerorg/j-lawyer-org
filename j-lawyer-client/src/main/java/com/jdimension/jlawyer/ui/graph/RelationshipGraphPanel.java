    // ---------------------------------------------------------------- layout
    private void startLayout() {
        this.layoutIterations = 0;
        this.temperature = INITIAL_TEMPERATURE;
        if (this.layoutTimer == null) {
            this.layoutTimer = new Timer(LAYOUT_TIMER_DELAY, new ActionListener() {
                @Override
                public void actionPerformed(ActionEvent e) {
                    layoutTick();
                }
            });
            this.layoutTimer.setRepeats(true);
        }
        if (this.nodes.size() < 2) {
            // nothing to arrange
            this.layoutTimer.stop();
            return;
        }
        this.layoutTimer.restart();
    }

    private void layoutTick() {
        double maxMovement = 0d;
        for (int i = 0; i < LAYOUT_ITERATIONS_PER_TICK; i++) {
            maxMovement = Math.max(maxMovement, this.layoutStep());
            this.layoutIterations++;
            if (this.layoutIterations >= LAYOUT_MAX_ITERATIONS) {
                break;
            }
        }

        boolean settled = maxMovement < LAYOUT_MOVEMENT_THRESHOLD;
        boolean exhausted = this.layoutIterations >= LAYOUT_MAX_ITERATIONS;
        if (settled || exhausted) {
            this.layoutTimer.stop();
            if (this.fitWhenSettled) {
                this.fitWhenSettled = false;
                this.zoomToFit();
            }
        }
        this.repaint();
    }

    /**
     * One iteration of the spring embedder.
     *
     * @return the largest distance any node was moved
     */
    private double layoutStep() {
        List<GraphNode> list = new ArrayList<>(this.nodes.values());
        int n = list.size();
        if (n < 2) {
            return 0d;
        }

        double[] dx = new double[n];
        double[] dy = new double[n];
        Map<String, Integer> index = new LinkedHashMap<>();
        for (int i = 0; i < n; i++) {
            index.put(list.get(i).getId(), i);
        }

        // repulsion between all pairs
        for (int i = 0; i < n; i++) {
            GraphNode a = list.get(i);
            for (int j = i + 1; j < n; j++) {
                GraphNode b = list.get(j);
                double vx = a.getX() - b.getX();
                double vy = a.getY() - b.getY();
                double d = Math.sqrt((vx * vx) + (vy * vy));
                if (d < 0.5d) {
                    // two nodes on top of each other: push them apart deterministically
                    vx = ((i % 7) - 3) + 0.5d;
                    vy = ((j % 7) - 3) + 0.5d;
                    d = Math.sqrt((vx * vx) + (vy * vy));
                }
                double force = (SPRING_LENGTH * SPRING_LENGTH) / d;
                double ux = vx / d;
                double uy = vy / d;
                dx[i] += ux * force;
                dy[i] += uy * force;
                dx[j] -= ux * force;
                dy[j] -= uy * force;
            }
        }

        // attraction along the edges
        for (GraphEdge e : this.edges.values()) {
            Integer fi = index.get(e.getFromNodeId());
            Integer ti = index.get(e.getToNodeId());
            if (fi == null || ti == null || fi.equals(ti)) {
                continue;
            }
            GraphNode a = list.get(fi);
            GraphNode b = list.get(ti);
            double vx = a.getX() - b.getX();
            double vy = a.getY() - b.getY();
            double d = Math.sqrt((vx * vx) + (vy * vy));
            if (d < 0.5d) {
                continue;
            }
            double force = (d * d) / SPRING_LENGTH;
            double ux = vx / d;
            double uy = vy / d;
            dx[fi] -= ux * force;
            dy[fi] -= uy * force;
            dx[ti] += ux * force;
            dy[ti] += uy * force;
        }

        // mild pull towards the centre, so unconnected parts do not drift away
        for (int i = 0; i < n; i++) {
            GraphNode a = list.get(i);
            dx[i] -= a.getX() * CENTERING_FORCE * SPRING_LENGTH;
            dy[i] -= a.getY() * CENTERING_FORCE * SPRING_LENGTH;
        }

        double maxMovement = 0d;
        for (int i = 0; i < n; i++) {
            GraphNode a = list.get(i);
            if (a.isPinned()) {
                continue;
            }
            double d = Math.sqrt((dx[i] * dx[i]) + (dy[i] * dy[i]));
            if (d < 0.0001d) {
                continue;
            }
            double step = Math.min(d, this.temperature);
            double mx = (dx[i] / d) * step;
            double my = (dy[i] / d) * step;
            a.setPosition(a.getX() + mx, a.getY() + my);
            maxMovement = Math.max(maxMovement, step);
        }

        this.temperature = Math.max(MIN_TEMPERATURE, this.temperature * COOLING_FACTOR);
        return maxMovement;
    }

    /**
     * Places all nodes that are not pinned on a golden angle spiral around the origin, which
     * gives the embedder an even, overlap free starting point.
     */
    private void seedPositions() {
        double goldenAngle = Math.PI * (3d - Math.sqrt(5d));
        int i = 0;
        for (GraphNode n : this.nodes.values()) {
            if (n.isPinned()) {
                continue;
            }
            if (n.getId() != null && n.getId().equals(this.rootNodeId)) {
                n.setPosition(0d, 0d);
                continue;
            }
            double radius = SPRING_LENGTH * 0.55d * Math.sqrt(i + 1d);
            double angle = i * goldenAngle;
            n.setPosition(Math.cos(angle) * radius, Math.sin(angle) * radius);
            i++;
        }
    }

    private void placeAroundCentre(GraphNode node, int ordinal) {
        double goldenAngle = Math.PI * (3d - Math.sqrt(5d));
        double radius = SPRING_LENGTH * 0.55d * Math.sqrt(ordinal + 1d);
        double angle = ordinal * goldenAngle;
        node.setPosition(Math.cos(angle) * radius, Math.sin(angle) * radius);
    }

    private void applyZoomToFit() {
        Rectangle2D bounds = this.graphBounds();
        if (bounds == null) {
            this.zoom = 1.0d;
            this.panX = this.getWidth() / 2.0d;
            this.panY = this.getHeight() / 2.0d;
            this.viewInitialised = true;
            return;
        }

        double margin = 40d;
        double availableWidth = Math.max(50d, this.getWidth() - (2d * margin));
        double availableHeight = Math.max(50d, this.getHeight() - (2d * margin));
        double scaleX = availableWidth / Math.max(1d, bounds.getWidth());
        double scaleY = availableHeight / Math.max(1d, bounds.getHeight());
        double newZoom = Math.min(scaleX, scaleY);
        newZoom = Math.max(MIN_ZOOM, Math.min(1.2d, newZoom));

        this.zoom = newZoom;
        this.panX = (this.getWidth() / 2.0d) - (bounds.getCenterX() * newZoom);
        this.panY = (this.getHeight() / 2.0d) - (bounds.getCenterY() * newZoom);
        this.viewInitialised = true;
    }

    private Rectangle2D graphBounds() {
        Rectangle2D bounds = null;
        for (GraphNode n : this.nodes.values()) {
            Rectangle2D b = this.nodeBounds(n);
            if (bounds == null) {
                bounds = new Rectangle2D.Double(b.getX(), b.getY(), b.getWidth(), b.getHeight());
            } else {
                bounds.add(b);
            }
        }
        return bounds;
    }

    // ---------------------------------------------------------------- geometry
    private Rectangle2D nodeBounds(GraphNode node) {
        FontMetrics fm = this.getFontMetrics(this.nodeFont);
        String label = node.getLabel() == null ? "" : node.getLabel();
        double width = fm.stringWidth(label) + 28d;
        width = Math.max(NODE_MIN_WIDTH, Math.min(NODE_MAX_WIDTH, width));
        double height = node.getKind() == GraphNode.Kind.CASE ? NODE_HEIGHT_CASE : NODE_HEIGHT_CONTACT;
        return new Rectangle2D.Double(node.getX() - (width / 2d), node.getY() - (height / 2d), width, height);
    }

    private Shape nodeShape(GraphNode node, Rectangle2D b) {
        if (node.getKind() == GraphNode.Kind.CASE) {
            // a folder like outline, clearly different from the rounded contact nodes
            double tabWidth = Math.min(38d, b.getWidth() * 0.42d);
            Path2D.Double p = new Path2D.Double();
            p.moveTo(b.getX(), b.getMaxY());
            p.lineTo(b.getX(), b.getY());
            p.lineTo(b.getX() + tabWidth, b.getY());
            p.lineTo(b.getX() + tabWidth + 6d, b.getY() + CASE_TAB_HEIGHT);
            p.lineTo(b.getMaxX(), b.getY() + CASE_TAB_HEIGHT);
            p.lineTo(b.getMaxX(), b.getMaxY());
            p.closePath();
            return p;
        }
        return new RoundRectangle2D.Double(b.getX(), b.getY(), b.getWidth(), b.getHeight(), 14d, 14d);
    }

    private Point2D toWorld(Point p) {
        return new Point2D.Double((p.x - this.panX) / this.zoom, (p.y - this.panY) / this.zoom);
    }

    private Color nodeColor(GraphNode node) {
        if (node.getColor() != null) {
            return node.getColor();
        }
        return node.getKind() == GraphNode.Kind.CASE ? CASE_DEFAULT : CONTACT_DEFAULT;
    }

    private Color edgeColor(GraphEdge edge) {
        if (edge.getColor() != null) {
            return edge.getColor();
        }
        return EDGE_DEFAULT;
    }

    private static Color lighten(Color c, double amount) {
        double f = Math.max(0d, Math.min(1d, amount));
        int r = (int) Math.round(c.getRed() + ((255 - c.getRed()) * f));
        int g = (int) Math.round(c.getGreen() + ((255 - c.getGreen()) * f));
        int b = (int) Math.round(c.getBlue() + ((255 - c.getBlue()) * f));
        return new Color(r, g, b);
    }

    private GraphNode nodeAt(Point p) {
        Point2D w = this.toWorld(p);
        List<GraphNode> list = new ArrayList<>(this.nodes.values());
        for (int i = list.size() - 1; i >= 0; i--) {
            GraphNode n = list.get(i);
            if (this.nodeBounds(n).contains(w)) {
                return n;
            }
        }
        return null;
    }

    private GraphEdge edgeAt(Point p) {
        Point2D w = this.toWorld(p);
        double tolerance = 6d / Math.max(MIN_ZOOM, this.zoom);
        for (GraphEdge e : this.edges.values()) {
            GraphNode a = this.nodes.get(e.getFromNodeId());
            GraphNode b = this.nodes.get(e.getToNodeId());
            if (a == null || b == null) {
                continue;
            }
            double d = Line2D.ptSegDist(a.getX(), a.getY(), b.getX(), b.getY(), w.getX(), w.getY());
            if (d <= tolerance) {
                return e;
            }
        }
        return null;
    }

    private boolean isExpandable(GraphNode node) {
        return node != null && !node.isExpanded() && this.actionListener != null;
    }

    private boolean isOnExpandBadge(GraphNode node, Point p) {
        if (!this.isExpandable(node)) {
            return false;
        }
        Rectangle2D b = this.nodeBounds(node);
        Point2D w = this.toWorld(p);
        double cx = b.getMaxX() - 3d;
        double cy = b.getY() + 3d;
        return Point2D.distance(cx, cy, w.getX(), w.getY()) <= (BADGE_RADIUS + 2d);
    }

    // ---------------------------------------------------------------- interaction
    private void handlePressed(MouseEvent e) {
        this.dragging = false;
        this.badgeNode = null;
        GraphNode node = this.nodeAt(e.getPoint());

        if (e.isPopupTrigger()) {
            this.showNodeMenu(node, e);
            return;
        }

        if (node != null) {
            this.selectedNode = node;
            if (this.isOnExpandBadge(node, e.getPoint())) {
                this.badgeNode = node;
            }
            this.draggedNode = node;
            Point2D w = this.toWorld(e.getPoint());
            this.dragOffsetX = w.getX() - node.getX();
            this.dragOffsetY = w.getY() - node.getY();
        } else {
            this.selectedNode = null;
            this.draggedNode = null;
            this.panStart = e.getPoint();
            this.panStartX = this.panX;
            this.panStartY = this.panY;
        }
        this.repaint();
    }

    private void handleDragged(MouseEvent e) {
        this.dragging = true;
        this.badgeNode = null;
        if (this.draggedNode != null) {
            Point2D w = this.toWorld(e.getPoint());
            this.draggedNode.setPosition(w.getX() - this.dragOffsetX, w.getY() - this.dragOffsetY);
            this.draggedNode.setPinned(true);
            this.repaint();
        } else if (this.panStart != null) {
            this.panX = this.panStartX + (e.getX() - this.panStart.x);
            this.panY = this.panStartY + (e.getY() - this.panStart.y);
            this.repaint();
        }
    }

    private void handleReleased(MouseEvent e) {
        if (e.isPopupTrigger()) {
            this.showNodeMenu(this.nodeAt(e.getPoint()), e);
        } else if (!this.dragging && this.badgeNode != null && e.getClickCount() <= 1) {
            GraphNode toExpand = this.badgeNode;
            this.badgeNode = null;
            this.draggedNode = null;
            this.panStart = null;
            this.fireNodeExpandRequested(toExpand);
            return;
        } else if (this.dragging && this.draggedNode != null) {
            // let the rest of the graph settle around the node the user has just placed
            this.fitWhenSettled = false;
            this.startLayout();
        }
        this.draggedNode = null;
        this.panStart = null;
        this.badgeNode = null;
    }

    private void handleClicked(MouseEvent e) {
        if (this.dragging || e.isPopupTrigger()) {
            return;
        }
        if (e.getClickCount() == 2) {
            GraphNode node = this.nodeAt(e.getPoint());
            if (node != null) {
                this.fireNodeOpened(node);
            }
        }
    }

    private void handleWheel(MouseWheelEvent e) {
        double rotation = e.getPreciseWheelRotation();
        if (rotation == 0d) {
            return;
        }
        double factor = rotation < 0d ? ZOOM_STEP : (1d / ZOOM_STEP);
        double newZoom = Math.max(MIN_ZOOM, Math.min(MAX_ZOOM, this.zoom * factor));
        if (Math.abs(newZoom - this.zoom) < 0.00001d) {
            return;
        }
        // keep the point under the cursor where it is
        double worldX = (e.getX() - this.panX) / this.zoom;
        double worldY = (e.getY() - this.panY) / this.zoom;
        this.zoom = newZoom;
        this.panX = e.getX() - (worldX * newZoom);
        this.panY = e.getY() - (worldY * newZoom);
        this.viewInitialised = true;
        this.repaint();
    }

    private void showNodeMenu(GraphNode node, MouseEvent e) {
        if (node == null || this.actionListener == null) {
            return;
        }
        this.popupNode = node;
        this.selectedNode = node;
        this.mnuExpand.setEnabled(!node.isExpanded());
        this.nodeMenu.show(this, e.getX(), e.getY());
        this.repaint();
    }

    private void fireNodeOpened(GraphNode node) {
        if (node != null && this.actionListener != null) {
            this.actionListener.nodeOpened(node);
        }
    }

    private void fireNodeExpandRequested(GraphNode node) {
        if (node != null && this.actionListener != null) {
            this.actionListener.nodeExpandRequested(node);
        }
    }

    @Override
    public String getToolTipText(MouseEvent event) {
        if (event == null) {
            return null;
        }
        GraphNode node = this.nodeAt(event.getPoint());
        if (node != null) {
            return node.getTooltip() == null ? node.getLabel() : node.getTooltip();
        }
        GraphEdge edge = this.edgeAt(event.getPoint());
        if (edge != null) {
            if (edge.getTooltip() != null) {
                return edge.getTooltip();
            }
            return edge.getLabel() == null || edge.getLabel().isEmpty() ? null : edge.getLabel();
        }
        return null;
    }

    // ---------------------------------------------------------------- painting
    @Override
    protected void paintComponent(Graphics g) {
        super.paintComponent(g);
        Graphics2D g2 = (Graphics2D) g.create();
        try {
            g2.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
            g2.setRenderingHint(RenderingHints.KEY_TEXT_ANTIALIASING, RenderingHints.VALUE_TEXT_ANTIALIAS_ON);
            g2.setRenderingHint(RenderingHints.KEY_STROKE_CONTROL, RenderingHints.VALUE_STROKE_PURE);

            if (!this.viewInitialised && this.getWidth() > 0) {
                this.panX = this.getWidth() / 2.0d;
                this.panY = this.getHeight() / 2.0d;
                this.viewInitialised = true;
            }
            if (this.fitPending && this.getWidth() > 0 && this.getHeight() > 0) {
                this.fitPending = false;
                this.applyZoomToFit();
            }

            if (this.nodes.isEmpty()) {
                this.paintEmptyState(g2);
                return;
            }

            Graphics2D scene = (Graphics2D) g2.create();
            try {
                scene.translate(this.panX, this.panY);
                scene.scale(this.zoom, this.zoom);
                this.paintEdges(scene);
                this.paintNodes(scene);
            } finally {
                scene.dispose();
            }

            this.paintOverlay(g2);
        } finally {
            g2.dispose();
        }
    }

    private void paintEmptyState(Graphics2D g2) {
        g2.setFont(this.nodeFont);
        g2.setColor(EMPTY_COLOR);
        String text = "keine Verknüpfungen vorhanden";
        FontMetrics fm = g2.getFontMetrics();
        int x = (this.getWidth() - fm.stringWidth(text)) / 2;
        int y = this.getHeight() / 2;
        g2.drawString(text, Math.max(10, x), y);
    }

    private void paintEdges(Graphics2D g2) {
        Stroke solid = new BasicStroke(1.6f, BasicStroke.CAP_ROUND, BasicStroke.JOIN_ROUND);
        Stroke solidHighlighted = new BasicStroke(2.6f, BasicStroke.CAP_ROUND, BasicStroke.JOIN_ROUND);
        Stroke dashed = new BasicStroke(1.6f, BasicStroke.CAP_BUTT, BasicStroke.JOIN_ROUND, 10f, new float[]{7f, 6f}, 0f);
        Stroke dashedHighlighted = new BasicStroke(2.6f, BasicStroke.CAP_BUTT, BasicStroke.JOIN_ROUND, 10f, new float[]{7f, 6f}, 0f);

        boolean withLabels = this.zoom >= 0.55d;

        for (GraphEdge e : this.edges.values()) {
            GraphNode a = this.nodes.get(e.getFromNodeId());
            GraphNode b = this.nodes.get(e.getToNodeId());
            if (a == null || b == null) {
                continue;
            }

            boolean highlighted = this.selectedNode != null
                    && (this.selectedNode == a || this.selectedNode == b);
            Color color = this.edgeColor(e);
            if (!highlighted) {
                color = lighten(color, 0.25d);
            }

            if (e.getKind() == GraphEdge.Kind.PARTICIPATION) {
                g2.setStroke(highlighted ? dashedHighlighted : dashed);
            } else {
                g2.setStroke(highlighted ? solidHighlighted : solid);
            }
            g2.setColor(color);
            g2.draw(new Line2D.Double(a.getX(), a.getY(), b.getX(), b.getY()));

            if (withLabels && e.getLabel() != null && !e.getLabel().isEmpty()) {
                this.paintEdgeLabel(g2, a, b, e);
            }
        }
        g2.setStroke(new BasicStroke(1f));
    }

    private void paintEdgeLabel(Graphics2D g2, GraphNode a, GraphNode b, GraphEdge e) {
        double dx = b.getX() - a.getX();
        double dy = b.getY() - a.getY();
        if ((Math.abs(dx) + Math.abs(dy)) < 1d) {
            return;
        }
        double angle = Math.atan2(dy, dx);
        if (angle > (Math.PI / 2d) || angle < (-Math.PI / 2d)) {
            // keep the text readable instead of upside down
            angle += Math.PI;
        }
        double midX = (a.getX() + b.getX()) / 2d;
        double midY = (a.getY() + b.getY()) / 2d;

        g2.setFont(this.edgeFont);
        FontMetrics fm = g2.getFontMetrics();
        String text = shorten(e.getLabel(), 32);
        int textWidth = fm.stringWidth(text);

        AffineTransform old = g2.getTransform();
        try {
            g2.translate(midX, midY);
            g2.rotate(angle);
            g2.setColor(new Color(250, 250, 250, 215));
            g2.fillRoundRect((-textWidth / 2) - 4, -fm.getAscent() - 4, textWidth + 8, fm.getHeight(), 8, 8);
            g2.setColor(EDGE_LABEL_COLOR);
            g2.drawString(text, -textWidth / 2, -5);
        } finally {
            g2.setTransform(old);
        }
    }

    private void paintNodes(Graphics2D g2) {
        g2.setFont(this.nodeFont);
        FontMetrics fm = g2.getFontMetrics();

        for (GraphNode node : this.nodes.values()) {
            Rectangle2D b = this.nodeBounds(node);
            Shape shape = this.nodeShape(node, b);
            Color color = this.nodeColor(node);
            boolean selected = node == this.selectedNode;
            boolean root = node.getId() != null && node.getId().equals(this.rootNodeId);

            g2.setColor(lighten(color, node.getKind() == GraphNode.Kind.CASE ? 0.86d : 0.8d));
            g2.fill(shape);

            g2.setColor(color);
            g2.setStroke(new BasicStroke(selected ? 2.6f : (root ? 2.0f : 1.2f)));
            g2.draw(shape);
            g2.setStroke(new BasicStroke(1f));

            String text = fit(node.getLabel(), fm, b.getWidth() - 16d);
            int textWidth = fm.stringWidth(text);
            double textX = b.getCenterX() - (textWidth / 2d);
            double textY = b.getCenterY() + (fm.getAscent() / 2d) - 1d;
            if (node.getKind() == GraphNode.Kind.CASE) {
                textY += CASE_TAB_HEIGHT / 2d;
            }
            g2.setColor(TEXT_COLOR);
            g2.drawString(text, (float) textX, (float) textY);

            if (this.isExpandable(node) && this.zoom >= 0.5d) {
                this.paintExpandBadge(g2, b, color);
            }
        }
    }

    private void paintExpandBadge(Graphics2D g2, Rectangle2D b, Color color) {
        double cx = b.getMaxX() - 3d;
        double cy = b.getY() + 3d;
        double r = BADGE_RADIUS;
        g2.setColor(Color.WHITE);
        g2.fillOval((int) Math.round(cx - r), (int) Math.round(cy - r), (int) Math.round(2 * r), (int) Math.round(2 * r));
        g2.setColor(color);
        g2.setStroke(new BasicStroke(1.2f));
        g2.drawOval((int) Math.round(cx - r), (int) Math.round(cy - r), (int) Math.round(2 * r), (int) Math.round(2 * r));
        g2.draw(new Line2D.Double(cx - 3.5d, cy, cx + 3.5d, cy));
        g2.draw(new Line2D.Double(cx, cy - 3.5d, cx, cy + 3.5d));
        g2.setStroke(new BasicStroke(1f));
    }

    private void paintOverlay(Graphics2D g2) {
        boolean hasParticipation = false;
        for (GraphEdge e : this.edges.values()) {
            if (e.getKind() == GraphEdge.Kind.PARTICIPATION) {
                hasParticipation = true;
                break;
            }
        }

        boolean hasExpandable = false;
        for (GraphNode n : this.nodes.values()) {
            if (this.isExpandable(n)) {
                hasExpandable = true;
                break;
            }
        }

        if (hasParticipation) {
            // tiny legend, so solid and dashed do not have to be guessed
            g2.setFont(this.edgeFont);
            FontMetrics fm = g2.getFontMetrics();
            int x = 12;
            int y = 18;
            g2.setColor(EDGE_DEFAULT);
            g2.setStroke(new BasicStroke(1.6f));
            g2.draw(new Line2D.Double(x, y - 4, x + 24, y - 4));
            g2.setColor(EDGE_LABEL_COLOR);
            g2.drawString("Beziehung", x + 30, y);

            y += fm.getHeight() + 2;
            g2.setColor(EDGE_DEFAULT);
            g2.setStroke(new BasicStroke(1.6f, BasicStroke.CAP_BUTT, BasicStroke.JOIN_ROUND, 10f, new float[]{7f, 6f}, 0f));
            g2.draw(new Line2D.Double(x, y - 4, x + 24, y - 4));
            g2.setStroke(new BasicStroke(1f));
            g2.setColor(EDGE_LABEL_COLOR);
            g2.drawString("Beteiligung", x + 30, y);
        }

        if (hasExpandable) {
            // the badge is the only element of the picture that is not self-explanatory
            g2.setFont(this.edgeFont);
            FontMetrics fm = g2.getFontMetrics();
            int x = 12;
            int y = hasParticipation ? 18 + 2 * (fm.getHeight() + 2) : 18;
            double cx = x + 7d;
            double cy = y - 4d;
            g2.setColor(Color.WHITE);
            g2.fillOval((int) Math.round(cx - BADGE_RADIUS), (int) Math.round(cy - BADGE_RADIUS),
                    (int) Math.round(2 * BADGE_RADIUS), (int) Math.round(2 * BADGE_RADIUS));
            g2.setColor(EDGE_DEFAULT);
            g2.setStroke(new BasicStroke(1.2f));
            g2.drawOval((int) Math.round(cx - BADGE_RADIUS), (int) Math.round(cy - BADGE_RADIUS),
                    (int) Math.round(2 * BADGE_RADIUS), (int) Math.round(2 * BADGE_RADIUS));
            g2.draw(new Line2D.Double(cx - 3.5d, cy, cx + 3.5d, cy));
            g2.draw(new Line2D.Double(cx, cy - 3.5d, cx, cy + 3.5d));
            g2.setStroke(new BasicStroke(1f));
            g2.setColor(EDGE_LABEL_COLOR);
            g2.drawString("weitere Beziehungen laden", x + 30, y);
        }

        if (this.truncated) {
            g2.setFont(this.hintFont);
            FontMetrics fm = g2.getFontMetrics();
            String text = this.truncationMessage;
            int x = 12;
            int y = this.getHeight() - 10;
            g2.setColor(new Color(255, 255, 255, 200));
            g2.fillRoundRect(x - 5, y - fm.getAscent() - 3, fm.stringWidth(text) + 10, fm.getHeight() + 4, 8, 8);
            g2.setColor(HINT_COLOR);
            g2.drawString(text, x, y);
        }
    }

    private static String shorten(String text, int maxChars) {
        if (text == null) {
            return "";
        }
        if (text.length() <= maxChars) {
            return text;
        }
        return text.substring(0, Math.max(1, maxChars - 1)) + "…";
    }

    private static String fit(String text, FontMetrics fm, double maxWidth) {
        if (text == null) {
            return "";
        }
        if (fm.stringWidth(text) <= maxWidth) {
            return text;
        }
        String shortened = text;
        while (shortened.length() > 1 && fm.stringWidth(shortened + "…") > maxWidth) {
            shortened = shortened.substring(0, shortened.length() - 1);
        }
        return shortened + "…";
    }

