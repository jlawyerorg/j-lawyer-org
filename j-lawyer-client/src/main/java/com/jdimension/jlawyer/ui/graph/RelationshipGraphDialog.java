    /**
     * The graph while it is being assembled: what is new, plus what is already on screen so the
     * node cap counts the whole picture and nothing is added twice.
     */
    private static class GraphData {

        private final Map<String, GraphNode> nodes = new LinkedHashMap<>();
        private final Map<String, GraphEdge> edges = new LinkedHashMap<>();
        private final Set<String> knownNodeIds = new HashSet<>();
        private final Set<String> relationIds = new HashSet<>();
        private boolean truncated = false;

        private GraphData(Set<String> existingNodeIds, Set<String> existingRelationIds) {
            if (existingNodeIds != null) {
                this.knownNodeIds.addAll(existingNodeIds);
            }
            if (existingRelationIds != null) {
                this.relationIds.addAll(existingRelationIds);
            }
        }

        private boolean hasNode(String nodeId) {
            return nodeId != null && this.knownNodeIds.contains(nodeId);
        }

        private GraphNode getNode(String nodeId) {
            return nodeId == null ? null : this.nodes.get(nodeId);
        }

        private void addNode(GraphNode node) {
            if (node == null || node.getId() == null) {
                return;
            }
            this.nodes.put(node.getId(), node);
            this.knownNodeIds.add(node.getId());
        }

        private void addEdge(GraphEdge edge) {
            if (edge != null) {
                this.edges.put(edge.getKey(), edge);
            }
        }

        private boolean capReached() {
            return this.knownNodeIds.size() >= RelationshipGraphPanel.MAX_NODES;
        }
    }

