import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.nio.file.attribute.PosixFilePermissions;
import java.util.Arrays;
import java.util.Locale;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Helpers for adjusting a database dump before it is restored.
 */
public class SqlDumpUtils {

    /**
     * Default collation of MySQL 8 that MariaDB before 11.4.5 does not know.
     */
    public static final String MYSQL8_DEFAULT_COLLATION = "utf8mb4_0900_ai_ci";

    /**
     * Replacement for {@link #MYSQL8_DEFAULT_COLLATION} that is available in MySQL and MariaDB.
     */
    public static final String PORTABLE_COLLATION = "utf8mb4_unicode_ci";

    private static final int BUFFER_SIZE = 64 * 1024;

    private SqlDumpUtils() {
    }

    /**
     * Writes a copy of a (possibly very large) dump written by mysqldump of MySQL 8 or MariaDB with its default
     * options, with a collation replaced in its SQL. The dump itself is not changed. Only the lines mysqldump writes are
     * accepted:
     * <ul>
     * <li>table data: INSERT INTO statements on one line (MySQL) or with one row per line (MariaDB). Every line ends
     * with ), or ); (the first one also with VALUES), line breaks in values are escaped. The collation may only occur
     * in strings, COLLATE, comments and a second statement are not allowed. Table data is never changed.</li>
     * <li>SET statements of simple assignments at the start of a statement, as in the header and trailer and around
     * views and triggers, also in an executable comment (/*!40101 SET ... *&#47;;): the value of collation_connection
     * or another collation_ variable is replaced. sql_mode may only be set to a literal of modes that do not change
     * how strings are read, saved from @@sql_mode or restored from a user variable whose name contains sql_mode.
     * NO_BACKSLASH_ESCAPES is accepted only for a trigger: in /*!50003 SET sql_mode = '...' *&#47; ; directly before
     * DELIMITER ;; and with /*!50003 SET sql_mode = @saved_sql_mode *&#47; ; directly after the trigger.</li>
     * <li>triggers: after DELIMITER ;; a trigger as mysqldump writes it (/*!50003 CREATE*&#47; ... /*!50003 TRIGGER
     * ...), with its strings read in the mode of the trigger, up to a line that ends with *&#47;;; outside of a
     * string, followed by DELIMITER ;. Triggers are never changed, the collation must not occur in them.</li>
     * <li>in all other lines (CREATE TABLE, views, comments) the collation is replaced where it follows COLLATE (COLLATE x
     * or COLLATE=x). Strings ('...' and "...", with backslash escapes), quoted identifiers (`...`) and comments are
     * never changed, the content of executable comments is SQL</li>
     * </ul>
     * Anything else makes the result uncertain and nothing is replaced: the collation anywhere else (in a string,
     * identifier or comment outside of table data, after something else than COLLATE), sql_mode or a collation_
     * variable in the code of other lines (or as a quoted name in another SET statement), other DELIMITER lines,
     * other commands of the mysql client, a string, identifier or comment that continues on the next line, a line that
     * ends with a qualifier (t.), a string in an executable comment that contains the end of the comment, a dump that
     * ends inside a statement or trigger or with an incomplete statement. Collation names are compared ignoring case.
     * <p>
     * The dump is processed as ISO-8859-1, so that every byte is written back unchanged - dumps may contain binary
     * data that is not valid UTF-8. The copy is created so that only its owner can read it (where the file system
     * supports POSIX permissions), it holds the whole database. It is only kept if the collation was replaced.
     *
     * @param dump the dump to read
     * @param target the copy to write, replaced if it exists
     * @param collation the collation to replace (ASCII)
     * @param replacement the new collation (ASCII)
     * @return the number of replaced occurrences, 0 if no copy was kept
     * @throws IOException if a file can not be read or written, no copy is kept then
     */
    public static long writeWithReplacedCollation(File dump, File target, String collation, String replacement) throws IOException {
        createForOwnerOnly(target.toPath());
        long count;
        try (Reader in = new InputStreamReader(new FileInputStream(dump), StandardCharsets.ISO_8859_1);
                Writer out = new OutputStreamWriter(Files.newOutputStream(target.toPath(), StandardOpenOption.WRITE, StandardOpenOption.TRUNCATE_EXISTING), StandardCharsets.ISO_8859_1)) {
            count = replaceCollation(in, out, collation, replacement);
        } catch (IOException ex) {
            Files.deleteIfExists(target.toPath());
            throw ex;
        }
        if (count > 0) {
            return count;
        }
        Files.delete(target.toPath());
        return 0;
    }

    /**
     * Counts where {@link #writeWithReplacedCollation(File, File, String, String)} would replace a collation, without
     * writing anything.
     *
     * @param dump the dump to read
     * @param collation the collation to look for (ASCII)
     * @return the number of occurrences that would be replaced, or -1 if the result is uncertain (then nothing would be
     * replaced)
     * @throws IOException if the dump can not be read
     */
    public static long countCollationUsages(File dump, String collation) throws IOException {
        try (Reader in = new InputStreamReader(new FileInputStream(dump), StandardCharsets.ISO_8859_1)) {
            return replaceCollation(in, Writer.nullWriter(), collation, collation);
        }
    }

    /**
     * Looks for a text anywhere in a dump, also in data and comments, ignoring case like
     * {@link #writeWithReplacedCollation(File, File, String, String)} does.
     *
     * @param dump the dump to read
     * @param text the text to look for (ASCII)
     * @return true if the dump contains the text
     * @throws IOException if the dump can not be read
     */
    public static boolean containsText(File dump, String text) throws IOException {
        Pattern pattern = Pattern.compile(Pattern.quote(text), Pattern.CASE_INSENSITIVE);
        try (Reader in = new InputStreamReader(new FileInputStream(dump), StandardCharsets.ISO_8859_1)) {
            char[] buffer = new char[BUFFER_SIZE];
            StringBuilder window = new StringBuilder();
            int read;
            while ((read = in.read(buffer)) != -1) {
                window.append(buffer, 0, read);
                if (pattern.matcher(window).find()) {
                    return true;
                }
                // keep the end, the text may continue in the next block
                window.delete(0, Math.max(0, window.length() - text.length() + 1));
            }
            return false;
        }
    }

    private static void createForOwnerOnly(Path file) throws IOException {
        Files.deleteIfExists(file);
        if (file.getFileSystem().supportedFileAttributeViews().contains("posix")) {
            Files.createFile(file, PosixFilePermissions.asFileAttribute(PosixFilePermissions.fromString("rw-------")));
        } else {
            Files.createFile(file);
        }
    }

    /**
     * Copies a dump from in to out and replaces the collation like {@link #writeWithReplacedCollation(File, File, String, String)}.
     *
     * @param in the dump
     * @param out receives the processed dump
     * @param collation the collation to replace
     * @param replacement the new collation
     * @return the number of replaced occurrences, or -1 if the result is uncertain (then the output must not be used)
     * @throws IOException if reading or writing fails
     */
    public static long replaceCollation(Reader in, Writer out, String collation, String replacement) throws IOException {
        return new DumpRewriter(in, out, collation, replacement).run();
    }

    /**
     * Copies a dump line by line and replaces the collation where mysqldump writes it.
     */
    private static final class DumpRewriter {

        /**
         * Table data: mysqldump escapes line breaks in values, so every line of an INSERT statement ends outside of a
         * string.
         */
        private static final String DATA = "INSERT INTO ";
        private static final int DATA_START = -2;
        private static final int TOO_LONG = -3;
        private static final int UNSAFE = -1;
        private static final int ROW_END = 0;
        private static final int ROWS_FOLLOW = 1;
        /**
         * Longer lines of SQL (not data) are not written by mysqldump.
         */
        private static final int MAX_LINE = 16 * 1024 * 1024;
        private static final String WORD = "[\\w$\\u0080-\\u00ff]";
        private static final String ASSIGNMENT = "(?:(@?\\w+)\\s*=\\s*('[\\w,:+\\-]*'|@{0,2}\\w+)|NAMES\\s+\\w+)";
        private static final String ASSIGNMENTS = ASSIGNMENT + "(?:\\s*,\\s*" + ASSIGNMENT + ")*";
        private static final Pattern SET = Pattern.compile("(?:/\\*!\\d{5}\\s+SET\\s+" + ASSIGNMENTS + "\\s*\\*/|SET\\s+" + ASSIGNMENTS + ")\\s*;\\s*", Pattern.CASE_INSENSITIVE);
        private static final Pattern SET_ASSIGNMENT = Pattern.compile(ASSIGNMENT, Pattern.CASE_INSENSITIVE);
        private static final Pattern SESSION_VARIABLE = Pattern.compile("sql_mode|collation_", Pattern.CASE_INSENSITIVE);
        private static final Pattern SET_START = Pattern.compile("\\s*(\\d{5,6}\\s+)?SET\\b", Pattern.CASE_INSENSITIVE);
        /**
         * The sql_mode of a trigger, its start and the restored sql_mode after it, as mysqldump writes them.
         */
        private static final Pattern TRIGGER_MODE = Pattern.compile("/\\*!50003 SET sql_mode\\s+= '[\\w,]*' \\*/ ;\\s*", Pattern.CASE_INSENSITIVE);
        private static final Pattern TRIGGER_START = Pattern.compile("DELIMITER ;;\\s*");
        private static final Pattern TRIGGER_HEADER = Pattern.compile("/\\*!50003 CREATE\\*/ (/\\*!50017 DEFINER=[^*]*\\*/ )?/\\*!50003 TRIGGER .*");
        private static final Pattern TRIGGER_MODE_RESTORED = Pattern.compile("/\\*!50003 SET sql_mode\\s+= @saved_sql_mode \\*/ ;\\s*", Pattern.CASE_INSENSITIVE);
        /**
         * Modes of MySQL 8.0 and MariaDB that do not change how strings, identifiers and comments are read (unlike
         * ANSI_QUOTES, NO_BACKSLASH_ESCAPES and the combinations ANSI, DB2, MAXDB, MSSQL, ORACLE and POSTGRESQL).
         */
        private static final Set<String> MODES = Set.of("ALLOW_INVALID_DATES", "ERROR_FOR_DIVISION_BY_ZERO", "HIGH_NOT_PRECEDENCE",
                "IGNORE_SPACE", "NO_AUTO_CREATE_USER", "NO_AUTO_VALUE_ON_ZERO", "NO_DIR_IN_CREATE", "NO_ENGINE_SUBSTITUTION",
                "NO_UNSIGNED_SUBTRACTION", "NO_ZERO_DATE", "NO_ZERO_IN_DATE", "ONLY_FULL_GROUP_BY", "PAD_CHAR_TO_FULL_LENGTH",
                "PIPES_AS_CONCAT", "REAL_AS_FLOAT", "STRICT_ALL_TABLES", "STRICT_TRANS_TABLES", "TIME_TRUNCATE_FRACTIONAL",
                "TRADITIONAL");

        private final Reader in;
        private final Writer out;
        private final String collation;
        private final String replacement;
        private final Pattern name;
        private final Pattern collate;
        private final char[] buffer = new char[BUFFER_SIZE];
        private int pos;
        private int limit;
        private boolean eof;
        private boolean statementStart = true;
        private boolean executableComment;
        private boolean triggerBody;
        private boolean triggerWithoutBackslashEscapes;
        private Pattern nextLine;
        private char triggerQuote;
        private boolean triggerEnded;
        private long count;
        private int lineCount;

        DumpRewriter(Reader in, Writer out, String collation, String replacement) {
            this.in = in;
            this.out = out;
            this.collation = collation;
            this.replacement = replacement;
            this.name = Pattern.compile(Pattern.quote(collation), Pattern.CASE_INSENSITIVE);
            this.collate = Pattern.compile("(?<!" + WORD + ")COLLATE(?:\\s+|\\s*=\\s*)(" + Pattern.quote(collation) + ")(?!" + WORD + ")", Pattern.CASE_INSENSITIVE);
        }

        long run() throws IOException {
            StringBuilder line = new StringBuilder();
            boolean data = false;
            while (true) {
                StringBuilder code = new StringBuilder();
                if (!data) {
                    int c = readLine(line, statementStart && !triggerBody && nextLine == null);
                    if (c == TOO_LONG) {
                        return -1;
                    }
                    if (c < 0 && line.length() == 0) {
                        break;
                    }
                    if (c != DATA_START) {
                        if (!process(line.toString())) {
                            return -1;
                        }
                        if (c < 0) {
                            break;
                        }
                        out.write('\n');
                        continue;
                    }
                    out.write(DATA);
                    code.append(DATA);
                }
                int end = copyData(code, !data);
                if (end == UNSAFE || (eof && end != ROW_END)) {
                    return -1;
                }
                data = end == ROWS_FOLLOW;
                if (eof) {
                    break;
                }
            }
            return executableComment || triggerBody || nextLine != null || !statementStart ? -1 : count;
        }

        /**
         * Reads a line without its line break, but stops after the start of table data if that is possible here.
         *
         * @return the line break, -1 at the end of the dump, {@link #DATA_START} or {@link #TOO_LONG}
         */
        private int readLine(StringBuilder line, boolean dataPossible) throws IOException {
            line.setLength(0);
            while (true) {
                if (dataPossible && line.length() == DATA.length() && DATA.contentEquals(line)) {
                    return DATA_START;
                }
                int c = read();
                if (c < 0 || c == '\n') {
                    return c;
                }
                if (line.length() == MAX_LINE) {
                    return TOO_LONG;
                }
                line.append((char) c);
            }
        }

        private int read() throws IOException {
            return pos < limit || fill() ? buffer[pos++] : -1;
        }

        private boolean fill() throws IOException {
            pos = 0;
            limit = Math.max(0, in.read(buffer, 0, buffer.length));
            eof = limit == 0;
            return !eof;
        }

        /**
         * Copies the rest of a line of table data unchanged. The collation may only occur in strings, comments are not
         * allowed, and the line has to end with a row (or with VALUES, if it is the first line of the statement).
         *
         * @param code the code before, outside of strings
         * @return {@link #ROW_END} if the statement ends here, {@link #ROWS_FOLLOW} if it continues on the next line,
         * {@link #UNSAFE} otherwise
         */
        private int copyData(StringBuilder code, boolean first) throws IOException {
            char quote = 0;
            boolean escaped = false;
            boolean closing = false;
            boolean ended = false;
            while (pos < limit || fill()) {
                int start = pos;
                while (pos < limit && buffer[pos] != '\n') {
                    char c = buffer[pos++];
                    if (quote != 0) {
                        if (escaped) {
                            escaped = false;
                            continue;
                        }
                        if (!closing) {
                            escaped = c == '\\';
                            closing = c == quote;
                            continue;
                        }
                        closing = false;
                        if (c == quote) {
                            // a doubled quote
                            continue;
                        }
                        quote = 0;
                    }
                    if (ended && !Character.isWhitespace(c)) {
                        // a second statement on the line
                        return UNSAFE;
                    }
                    ended |= c == ';';
                    if (c == '\'' || c == '"') {
                        quote = c;
                        c = '\0';
                    }
                    if (!dataCode(code, c)) {
                        return UNSAFE;
                    }
                }
                boolean lineEnd = pos < limit;
                if (lineEnd) {
                    pos++;
                }
                out.write(buffer, start, pos - start);
                if (lineEnd) {
                    break;
                }
            }
            if (quote != 0 && !closing) {
                return UNSAFE;
            }
            int end = code.length();
            while (end > 0 && Character.isWhitespace(code.charAt(end - 1))) {
                end--;
            }
            String last = code.substring(Math.max(0, end - 8), end);
            if (last.endsWith(");")) {
                return ROW_END;
            }
            return last.endsWith("),") || (first && last.endsWith(" VALUES")) ? ROWS_FOLLOW : UNSAFE;
        }

        /**
         * A character of table data outside of strings.
         *
         * @return false if it starts a comment or ends the collation or COLLATE
         */
        private boolean dataCode(StringBuilder code, char c) {
            char previous = code.length() == 0 ? ' ' : code.charAt(code.length() - 1);
            code.append(c);
            if (c == '#' || (c == '*' && previous == '/') || (c == '-' && previous == '-')) {
                return false;
            }
            int n = collation.length();
            if (Character.toLowerCase(c) == Character.toLowerCase(collation.charAt(n - 1)) && code.length() >= n && code.substring(code.length() - n).equalsIgnoreCase(collation)) {
                return false;
            }
            int k = code.length() - 9;
            if (k >= 0 && !isWordChar(code.charAt(k)) && !isWordChar(c) && code.substring(k + 1, k + 8).equalsIgnoreCase("COLLATE")) {
                return false;
            }
            if (code.length() > 4 * n) {
                code.delete(0, code.length() - n);
            }
            return true;
        }

        /**
         * Writes a line (without its line break) with the collation replaced.
         *
         * @return false if the result is uncertain
         */
        private boolean process(String line) throws IOException {
            lineCount = 0;
            String trimmed = line.stripTrailing();
            Pattern expected = nextLine;
            nextLine = null;
            String result;
            if (expected != null && !expected.matcher(line).matches()) {
                return false;
            } else if (triggerEnded) {
                if (!trimmed.equals("DELIMITER ;")) {
                    return false;
                }
                triggerBody = false;
                triggerEnded = false;
                statementStart = true;
                if (triggerWithoutBackslashEscapes) {
                    nextLine = TRIGGER_MODE_RESTORED;
                    triggerWithoutBackslashEscapes = false;
                }
                result = line;
            } else if (triggerBody) {
                // never changed, strings are read with the mode of the trigger, it ends with */;; outside of a string
                triggerQuote = openQuote(line, triggerQuote, !triggerWithoutBackslashEscapes);
                triggerEnded = triggerQuote == 0 && trimmed.endsWith("*/;;");
                result = line;
            } else if (trimmed.strip().regionMatches(true, 0, "DELIMITER", 0, 9)) {
                if (!statementStart || !TRIGGER_START.matcher(line).matches()) {
                    return false;
                }
                triggerBody = true;
                nextLine = TRIGGER_HEADER;
                result = line;
            } else if (statementStart && SET.matcher(line).matches()) {
                result = setStatement(line);
            } else {
                result = sql(line);
            }
            int occurrences = 0;
            for (Matcher m = name.matcher(line); m.find();) {
                occurrences++;
            }
            if (result == null || occurrences != lineCount) {
                return false;
            }
            count += lineCount;
            out.write(result);
            return true;
        }

        /**
         * A SET statement of only simple assignments, like those of mysqldump.
         */
        private String setStatement(String line) {
            StringBuilder result = new StringBuilder(line.length());
            int copied = 0;
            Matcher assignment = SET_ASSIGNMENT.matcher(line);
            while (assignment.find()) {
                String variable = assignment.group(1) == null ? "" : assignment.group(1).toLowerCase(Locale.ROOT);
                String value = assignment.group(2) == null ? "" : assignment.group(2).toLowerCase(Locale.ROOT);
                if (variable.contains("sql_mode")) {
                    boolean known = variable.startsWith("@") ? "@@sql_mode".equals(value)
                            : value.startsWith("'") ? knownModes(line, value)
                            : value.startsWith("@") && !value.startsWith("@@") && value.contains("sql_mode");
                    if (!known) {
                        return null;
                    }
                } else if (variable.contains("collation_") && value.equalsIgnoreCase(collation)) {
                    result.append(line, copied, assignment.start(2)).append(replacement);
                    copied = assignment.end(2);
                    lineCount++;
                }
            }
            return result.append(line, copied, line.length()).toString();
        }

        /**
         * Only modes that do not change how strings are read. NO_BACKSLASH_ESCAPES only as the mode of a trigger:
         * directly before DELIMITER ;; and restored directly after the trigger, as mysqldump writes it.
         */
        private boolean knownModes(String line, String literal) {
            boolean withoutBackslashEscapes = false;
            for (String mode : literal.substring(1, literal.length() - 1).toUpperCase(Locale.ROOT).split(",")) {
                if ("NO_BACKSLASH_ESCAPES".equals(mode) && TRIGGER_MODE.matcher(line).matches()) {
                    withoutBackslashEscapes = true;
                } else if (!mode.isEmpty() && !MODES.contains(mode)) {
                    return false;
                }
            }
            if (withoutBackslashEscapes) {
                nextLine = TRIGGER_START;
                triggerWithoutBackslashEscapes = true;
            }
            return true;
        }

        /**
         * Any other line of SQL: the collation is replaced after COLLATE, outside of strings, identifiers and comments.
         */
        private String sql(String line) {
            boolean start = statementStart;
            // the line with strings and identifiers blanked out by \0 and comments by spaces
            char[] code = line.toCharArray();
            int lastCode = -1;
            int i = 0;
            while (i < code.length) {
                char c = code[i];
                char next = i + 1 < code.length ? code[i + 1] : ' ';
                if (c == '\'' || c == '"' || c == '`') {
                    int close = closingQuote(line, i + 1, c, true);
                    int commentEnd = line.indexOf("*/", i);
                    if (close < 0 || (executableComment && commentEnd >= 0 && commentEnd < close)) {
                        // continues on the next line, or ends a comment for servers that ignore the executable comment
                        return null;
                    }
                    Arrays.fill(code, i, close + 1, '\0');
                    lastCode = c;
                    i = close + 1;
                } else if (c == '#' || (c == '-' && next == '-' && (i + 2 == code.length || code[i + 2] <= ' '))) {
                    if (executableComment) {
                        return null;
                    }
                    Arrays.fill(code, i, code.length, ' ');
                    break;
                } else if (c == '/' && next == '*') {
                    if (executableComment) {
                        return null;
                    }
                    int marker = line.startsWith("/*!", i) ? 3 : line.startsWith("/*M!", i) ? 4 : 0;
                    int close = marker > 0 ? i + marker : line.indexOf("*/", i + 2) + 2;
                    if (close < 2) {
                        return null;
                    }
                    executableComment = marker > 0;
                    Arrays.fill(code, i, close, ' ');
                    i = close;
                } else if (c == '*' && next == '/' && executableComment) {
                    executableComment = false;
                    Arrays.fill(code, i, i + 2, ' ');
                    i += 2;
                } else if (c == '\\' && next != '-') {
                    // a command of the mysql client, e.g. \d to change the delimiter (\- is the sandbox mode of MariaDB)
                    return null;
                } else {
                    if (c > ' ') {
                        lastCode = c;
                    }
                    i++;
                }
            }
            if (lastCode == '.') {
                // a qualified name that continues on the next line
                return null;
            }
            if (executableComment) {
                statementStart = false;
            } else if (lastCode >= 0) {
                statementStart = lastCode == ';';
            }
            String masked = new String(code);
            if (SESSION_VARIABLE.matcher(masked).find() || (start && SET_START.matcher(masked).lookingAt() && line.indexOf('`') >= 0)) {
                // sql_mode or a collation variable outside of a SET statement as mysqldump writes it, also as a quoted name
                return null;
            }
            StringBuilder result = new StringBuilder(line.length());
            int copied = 0;
            Matcher m = collate.matcher(masked);
            while (m.find()) {
                int before = m.start() - 1;
                while (before >= 0 && Character.isWhitespace(code[before])) {
                    before--;
                }
                if (before >= 0 && code[before] == '.') {
                    // a column named collate (t.collate), not the keyword
                    continue;
                }
                result.append(line, copied, m.start(1)).append(replacement);
                copied = m.end(1);
                lineCount++;
            }
            return result.append(line, copied, line.length()).toString();
        }

        /**
         * @return the index of the quote that ends a string or identifier, searched from the index from on, -1 if
         * there is none in this line
         */
        private static int closingQuote(String line, int from, char quote, boolean backslashEscapes) {
            for (int i = from; i < line.length(); i++) {
                char c = line.charAt(i);
                if (c == '\\' && backslashEscapes && quote != '`') {
                    i++;
                } else if (c == quote) {
                    if (i + 1 < line.length() && line.charAt(i + 1) == quote) {
                        i++;
                    } else {
                        return i;
                    }
                }
            }
            return -1;
        }

        /**
         * @param quote the quote of a string that continues from the line before, 0 if none
         * @return the quote of a string that continues on the next line, 0 if none
         */
        private static char openQuote(String line, char quote, boolean backslashEscapes) {
            int i = 0;
            while (true) {
                if (quote != 0) {
                    int close = closingQuote(line, i, quote, backslashEscapes);
                    if (close < 0) {
                        return quote;
                    }
                    quote = 0;
                    i = close + 1;
                }
                for (; i < line.length() && quote == 0; i++) {
                    char c = line.charAt(i);
                    if (c == '#' || (c == '-' && line.startsWith("-", i + 1) && (i + 2 == line.length() || line.charAt(i + 2) <= ' '))) {
                        return 0;
                    }
                    if (c == '\'' || c == '"' || c == '`') {
                        quote = c;
                    }
                }
                if (quote == 0) {
                    return 0;
                }
            }
        }

        private static boolean isWordChar(char c) {
            return Character.isLetterOrDigit(c) || c == '_' || c == '$' || c >= 0x80;
        }
    }
}
